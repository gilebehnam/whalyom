const brand = path.join(root, 'assets', 'brand');
const r2 = (n) => (Math.round(n * 100) / 100).toString();

export const GOLD = '#AD9570';   // brand kit brass
export const CREAM = '#D5D3C8';  // brand kit ivory
export const NIGHT = '#090D10';  // brand kit ink

// ── geometry (100 × 100 viewBox, centre 50,50; angles in degrees clockwise from 12 o'clock) ──
const SW = 4.4;                         // ring stroke
const R = { outer: 44, mid: 33, inner: 23 };
const STEM = 6.8;                         // half the gap between the two stem bars (the tail's stock)
const pt = (r, a) => [50 + r * Math.sin(a * Math.PI / 180), 50 - r * Math.cos(a * Math.PI / 180)];
const arc = (r, a0, a1) => { const [x0, y0] = pt(r, a0); const [x1, y1] = pt(r, a1); const sweep = a1 > a0 ? 1 : 0; const large = Math.abs(a1 - a0) > 180 ? 1 : 0; return { start: `M${r2(x0)} ${r2(y0)}`, to: `A${r} ${r} 0 ${large} ${sweep} ${r2(x1)} ${r2(y1)}`, end: [x1, y1] }; };
// the angle (measured from 6 o'clock) where a ring of radius r reaches the vertical line x = 50 ± d
const atX = (r, d) => Math.asin(d / r) * 180 / Math.PI;

export function markPaths() {
  const P = [];
  const side = (s) => { // s = -1 left, +1 right
    // middle ring, lower part: from under the fluke tip down to the stem line, then a U-turn into the outer ring
    const xMid = STEM + SW + 2.2;
    const aMid = 180 - atX(R.mid, xMid);
    const m = arc(R.mid, s * 118, s * aMid);
    const yOuter = 50 + Math.sqrt(R.outer ** 2 - xMid ** 2);
    const outerA = 180 - atX(R.outer, xMid);
    // outer ring: the left side runs up past 12 o'clock to 20°, the right side up to 68° (below the gold arc)
    const outerTo = s < 0 ? arc(R.outer, -outerA, 20) : arc(R.outer, outerA, 68);
    P.push(`${m.start} ${m.to} L${r2(50 + s * xMid)} ${r2(yOuter)} ${outerTo.to}`);
    // inner ring, lower part: from under the fluke down into the stem bar
    const aIn = 180 - atX(R.inner, STEM + SW / 2);
    const i = arc(R.inner, s * 126, s * aIn);
    P.push(`${i.start} ${i.to} L${r2(50 + s * (STEM + SW / 2))} ${r2(50 + R.outer + SW / 2 - 0.4)}`);
  };
  side(-1); side(1);
  const top = (r, a) => { const t = arc(r, -a, a); return `${t.start} ${t.to}`; };
  P.push(top(R.mid, 48), top(R.inner, 40));
  return P;
}
export const goldArc = () => { const g = arc(R.outer, 27, 61); return `${g.start} ${g.to}`; };
export const TAIL = 'M50 54C46 50.5 41 47.6 34 46.6C26 45.6 21 42.2 18 37.2C17.6 46 23 53 31 56.6C37 59.2 41 62 43.6 68.4C45.6 63.2 48 59.6 50 58.6C52 59.6 54.4 63.2 56.4 68.4C59 62 63 59.2 69 56.6C77 53 82.4 46 82 37.2C79 42.2 74 45.6 66 46.6C59 47.6 54 50.5 50 54Z';

export function markInner({ color = 'currentColor', gold = GOLD } = {}) {
  return `<g fill="none" stroke="${color}" stroke-width="${SW}" stroke-linecap="butt" stroke-linejoin="miter">${markPaths().map((d) => `<path d="${d}"/>`).join('')}</g>` +
    `<path d="${goldArc()}" fill="none" stroke="${gold}" stroke-width="${SW}" stroke-linecap="butt"/>` +
    `<path d="${TAIL}" fill="${color}"/>`;
}
export const markSvg = (opts = {}) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" role="img" aria-label="Whalyom">
  <title>Whalyom</title>
  <!-- A round maze of three rings opened by a whale's tail; the gold arc is the one step ahead. Generated by tools/make-logo.mjs -->
  ${markInner(opts)}
</svg>
`;

// ── the wordmark WHA⅃YOM: geometric stroked capitals, cap height 40, the L mirrored ──
const LS = 8.5;                            // letter stroke
const LETTERS = {
  W: [56, 'M0 0L14 40L28 9L42 40L56 0'],
  H: [34, 'M0 0V40M34 0V40M0 21H34'],
  A: [42, 'M0 40L21 0L42 40M10.5 30H31.5'],
  J: [28, 'M28 0V40H0'],                 // the mirrored L
  Y: [40, 'M0 0L20 21L40 0M20 21V40'],
  O: [40, 'M4.25 20a15.75 15.75 0 1 0 31.5 0a15.75 15.75 0 1 0 -31.5 0'],
  M: [44, 'M0 40V0L22 25L44 0V40'],
};
export function wordmark({ color = 'currentColor', x = 0, y = 0, scale = 1 } = {}) {
  let cx = LS / 2; const parts = [];
  for (const ch of 'WHAJYOM') {
    const [w, d] = LETTERS[ch];
    parts.push(ch === 'O' ? `<circle cx="${r2(cx + 20)}" cy="${r2(LS / 2 + 20)}" r="${r2(20 - LS / 2)}"/>` : `<path transform="translate(${r2(cx)} ${LS / 2})" d="${d}"/>`);
    cx += w + 13;
  }
  const width = cx - 13 + LS / 2;
  return { width, height: 40 + LS, svg: `<g transform="translate(${r2(x)} ${r2(y)}) scale(${scale})" fill="none" stroke="${color}" stroke-width="${LS}" stroke-linejoin="miter" stroke-miterlimit="8" stroke-linecap="butt">${parts.join('')}</g>` };
}
export const lockupSvg = ({ color = 'currentColor' } = {}) => {
  const w = wordmark({ color, x: 128, y: 31.5, scale: 0.8 });
  const W = 128 + w.width * 0.8 + 8;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r2(W)} 100" role="img" aria-label="Whalyom"><title>Whalyom</title>${markInner({ color })}${w.svg}</svg>\n`;
};
export const stackedSvg = ({ color = 'currentColor' } = {}) => {
  const w = wordmark({ color, scale: 0.6 }); const ww = w.width * 0.6; const W = Math.max(110, ww + 10);
  const wm = wordmark({ color, x: (W - ww) / 2, y: 112, scale: 0.6 });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r2(W)} ${r2(112 + w.height * 0.6 + 4)}" role="img" aria-label="Whalyom"><title>Whalyom</title><g transform="translate(${r2((W - 100) / 2)} 0)">${markInner({ color })}</g>${wm.svg}</svg>\n`;
};
