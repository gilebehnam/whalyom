// ── PNG through a local headless browser (dev only) ──
function findBrowser() {
  const c = [process.env.CHROME_PATH, 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Google/Chrome/Application/chrome.exe', '/usr/bin/google-chrome', '/usr/bin/chromium', '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'];
  return c.find((p) => p && fs.existsSync(p));
}
async function renderPngs(svg, sizes) {
  const exe = findBrowser(); if (!exe) throw new Error('no Edge or Chrome found (set CHROME_PATH)');
  const port = 9600 + Math.floor(Math.random() * 300);
  const prof = path.join(process.env.TEMP ?? '/tmp', `wy-logo-${port}`);
  const p = spawn(exe, ['--headless=new', '--disable-gpu', `--remote-debugging-port=${port}`, `--user-data-dir=${prof}`, 'about:blank'], { stdio: 'ignore' });
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  try {
    let list; for (let i = 0; i < 60 && !list; i++) { await sleep(200); try { list = await (await fetch(`http://127.0.0.1:${port}/json`)).json(); } catch { /* starting */ } }
    const ws = new WebSocket(list.find((t) => t.type === 'page').webSocketDebuggerUrl);
    await new Promise((r) => ws.addEventListener('open', r));
    let id = 0; const wait = new Map();
    ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && wait.has(m.id)) { wait.get(m.id)(m); wait.delete(m.id); } });
    const cdp = (method, params = {}) => new Promise((r) => { const i = ++id; wait.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
    await cdp('Emulation.setDefaultBackgroundColorOverride', { color: { r: 0, g: 0, b: 0, a: 0 } });
    const out = {};
    for (const S of sizes) {
      await cdp('Emulation.setDeviceMetricsOverride', { width: S, height: S, deviceScaleFactor: 1, mobile: false });
      await cdp('Page.navigate', { url: `data:text/html,${encodeURIComponent(`<html><body style="margin:0;background:transparent">${svg.replace('<svg ', `<svg width="${S}" height="${S}" `)}</body></html>`)}` });
      await sleep(400);
      const s = await cdp('Page.captureScreenshot', { format: 'png', clip: { x: 0, y: 0, width: S, height: S, scale: 1 } });
      out[S] = Buffer.from(s.result.data, 'base64');
    }
    ws.close();
    return out;
  } finally { p.kill(); }
}
const ico = (pngs) => {
  const head = Buffer.from([0, 0, 1, 0, pngs.length, 0]); let off = 6 + 16 * pngs.length;
  const dir = pngs.map(([S, buf]) => { const d = Buffer.alloc(16); d[0] = S >= 256 ? 0 : S; d[1] = S >= 256 ? 0 : S; d.writeUInt16LE(1, 4); d.writeUInt16LE(32, 6); d.writeUInt32LE(buf.length, 8); d.writeUInt32LE(off, 12); off += buf.length; return d; });
  return Buffer.concat([head, ...dir, ...pngs.map(([, b]) => b)]);
};

