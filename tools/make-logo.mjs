// The Whalyom logo (2026-11): a round maze of three rings opened by a whale's tail, with one gold
// arc at the top right. One geometry, every output:
//   node tools/make-logo.mjs [--live] [--png]
//     assets/brand/whalyom-mark.svg          the mark in currentColor, the gold arc fixed
//     assets/brand/whalyom-mark-mono.svg     one flat colour, for stamps and print
//     assets/brand/whalyom-lockup.svg        mark + WHA⅃YOM side by side
//     assets/brand/whalyom-lockup-stacked.svg  mark above WHA⅃YOM
//     assets/brand/favicon.svg               the mark on a night tile
//   --live   also puts the mark and the favicon into live/index.html (the Command Center masthead)
//   --png    also renders tools/whalyom.png (256 px), tools/whalyom.ico (16/32/48/256) and the PWA
//            icons, through a local headless Edge or Chrome (CHROME_PATH to choose one)
// tools/make-icon-whale.mjs (the earlier three-circle mark) is kept but no longer owns these files.
